"""
Liver Cirrhosis Stage Prediction — Streamlit App
--------------------------------------------------
Loads the trained Stacking model (best_stacking_model.pkl), the fitted
StandardScaler, and the LabelEncoder produced by the training notebook,
then lets a user enter a patient's clinical/lab values and get a
predicted disease stage.

Run with:
    streamlit run app.py

Requires 'best_stacking_model.pkl', 'scaler.pkl', and 'label_encoder.pkl'
to be in the same folder (generated by running liver_cirrhosis_project.ipynb).
"""

import numpy as np
import pandas as pd
import streamlit as st
import joblib

# ----------------------------------------------------------------------
# Page setup
# ----------------------------------------------------------------------
st.set_page_config(page_title="Liver Cirrhosis Stage Predictor", page_icon="🩺", layout="centered")
st.title("🩺 Liver Cirrhosis Stage Predictor")
st.write(
    "Enter the patient's clinical and lab values below to predict the "
    "stage of liver cirrhosis using the trained Stacking ensemble model."
)
st.info(
    "⚠️ This tool is for educational/portfolio purposes only and is **not** "
    "a substitute for professional medical diagnosis.",
    icon="⚠️",
)

# ----------------------------------------------------------------------
# Load model artifacts (cached so they're loaded only once)
# ----------------------------------------------------------------------
@st.cache_resource
def load_artifacts():
    model = joblib.load("best_stacking_model.pkl")
    scaler = joblib.load("scaler.pkl")
    le = joblib.load("label_encoder.pkl")
    return model, scaler, le


try:
    model, scaler, le = load_artifacts()
except FileNotFoundError as e:
    st.error(
        "Could not find the model files. Make sure 'best_stacking_model.pkl', "
        "'scaler.pkl', and 'label_encoder.pkl' are in the same folder as app.py "
        "(run the training notebook first to generate them).\n\n"
        f"Details: {e}"
    )
    st.stop()

# The exact feature order the model was trained on
FEATURE_ORDER = [
    "N_Days_of suffering", "Bilirubin", "Cholesterol", "Albumin", "Copper",
    "Alk_Phos", "SGOT", "Tryglicerides", "Platelets", "Prothrombin",
    "Drug_Placebo", "Sex_M", "Ascites_Y", "Hepatomegaly_Y", "Spiders_Y",
    "Edema_S", "Age_in_years", "APRI", "Bilirubin_Albumin_ratio",
    "log_Bilirubin", "log_Cholesterol", "log_Copper", "log_Alk_Phos",
    "log_Tryglicerides",
]

# ----------------------------------------------------------------------
# Input form
# ----------------------------------------------------------------------
with st.form("patient_form"):
    st.subheader("Patient Info")
    col1, col2 = st.columns(2)
    with col1:
        age_years = st.number_input("Age (years)", min_value=1.0, max_value=120.0, value=50.0, step=1.0)
        sex = st.selectbox("Sex", ["F", "M"])
        drug = st.selectbox("Drug", ["D-penicillamine", "Placebo"])
        n_days = st.number_input("N Days of suffering", min_value=0, value=2000, step=10)
    with col2:
        ascites = st.selectbox("Ascites", ["N", "Y"])
        hepatomegaly = st.selectbox("Hepatomegaly", ["N", "Y"])
        spiders = st.selectbox("Spiders", ["N", "Y"])
        edema = st.selectbox("Edema", ["N", "S", "Y"])

    st.subheader("Lab Values")
    col3, col4, col5 = st.columns(3)
    with col3:
        bilirubin = st.number_input("Bilirubin", min_value=0.0, value=1.0, step=0.1, format="%.2f")
        cholesterol = st.number_input("Cholesterol", min_value=0.0, value=250.0, step=1.0)
        albumin = st.number_input("Albumin", min_value=0.0, value=3.5, step=0.1, format="%.2f")
    with col4:
        copper = st.number_input("Copper", min_value=0.0, value=80.0, step=1.0)
        alk_phos = st.number_input("Alk Phos", min_value=0.0, value=1000.0, step=1.0)
        sgot = st.number_input("SGOT", min_value=0.0, value=120.0, step=1.0)
    with col5:
        tryglicerides = st.number_input("Tryglicerides", min_value=0.0, value=120.0, step=1.0)
        platelets = st.number_input("Platelets", min_value=1.0, value=260.0, step=1.0)
        prothrombin = st.number_input("Prothrombin", min_value=0.0, value=10.5, step=0.1, format="%.2f")

    submitted = st.form_submit_button("Predict Stage")

# ----------------------------------------------------------------------
# Build feature vector + predict
# ----------------------------------------------------------------------
if submitted:
    # Recreate the same feature engineering pipeline used in training
    row = {
        "N_Days_of suffering": n_days,
        "Bilirubin": bilirubin,
        "Cholesterol": cholesterol,
        "Albumin": albumin,
        "Copper": copper,
        "Alk_Phos": alk_phos,
        "SGOT": sgot,
        "Tryglicerides": tryglicerides,
        "Platelets": platelets,
        "Prothrombin": prothrombin,
        "Drug_Placebo": 1 if drug == "Placebo" else 0,
        "Sex_M": 1 if sex == "M" else 0,
        "Ascites_Y": 1 if ascites == "Y" else 0,
        "Hepatomegaly_Y": 1 if hepatomegaly == "Y" else 0,
        "Spiders_Y": 1 if spiders == "Y" else 0,
        "Edema_S": 1 if edema == "S" else 0,
        "Age_in_years": age_years,
        "APRI": (sgot / 40) / platelets * 100,
        "Bilirubin_Albumin_ratio": bilirubin / albumin,
        "log_Bilirubin": np.log1p(bilirubin),
        "log_Cholesterol": np.log1p(cholesterol),
        "log_Copper": np.log1p(copper),
        "log_Alk_Phos": np.log1p(alk_phos),
        "log_Tryglicerides": np.log1p(tryglicerides),
    }

    X_input = pd.DataFrame([row])[FEATURE_ORDER]

    # NOTE: the Stacking model (RF + XGBoost + LightGBM base learners) was
    # trained on the *unscaled* features, so we predict directly here.
    # The scaler is loaded/available for other models (LR, SVM, KNN) that
    # do require scaled input, if you extend this app to support them.
    pred_encoded = model.predict(X_input)[0]
    pred_label = le.inverse_transform([pred_encoded])[0]

    proba = None
    if hasattr(model, "predict_proba"):
        proba = model.predict_proba(X_input)[0]

    st.subheader("Result")
    st.success(f"Predicted Stage of Disease: **{pred_label}**")

    if proba is not None:
        proba_df = pd.DataFrame({
            "Stage": le.inverse_transform(np.arange(len(proba))),
            "Probability": proba,
        }).sort_values("Probability", ascending=False)
        st.write("Prediction confidence:")
        st.bar_chart(proba_df.set_index("Stage"))
